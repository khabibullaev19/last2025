package pack04operators;

public class Operators {

    /*

        - Operators are an essential part of any programming language.
          In Java, operator is a symbol that is used to perform operations.
          For example: + , - , * , / , etc. These are essential for performing
          different types of operations on variables and values.

          There are mainly 8 types of operators in Java:
          1. Unary Operator
          2. Arithmetic Operator
          3. Relational Operator
          4. Ternary Operator
          5. Assignment Operator
          6. Bitwise Operator
          7. Logical Operator
          8. Shift Operator

     */

    /*

        " + " -> Unary Plus => Unary Plus operator; indicates positive value
                 (numbers are positive without this, however)

        " - " -> Unary Minus => The Unary Minus operator can be used to
                 make a positive value negative.

        " ! " -> Logical Complement Operator => The Not Operator is used to convert a
                 boolean value. In other words, it is used to reverse the logical state of
                 an operand.

        " ++ " -> Increment => It is used to increase the value of an operand by one.
                  It can be done in two possible ways. One is post-increment(operand++)
                  and other is pre-increment(++operand).

                  In post-increment, the value of the operand is used first,
                  then its value is increased by one.

                  In pre-increment, the value of the operand is incremented first by one,
                  then the incremented value of the operand is used.

     */

}
